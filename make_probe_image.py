#!/usr/bin/env python3
"""Assemble a diagnostic boot image from a self-generated probe shim + the FD.

Why this exists: the stock BootShim.S copies the FD to FD_BASE and jumps with
no output at all. On the first hardware attempt the phone came back to Android
with no pstore record of our code, so the failure is either "never executed"
or "executed and faulted before anything could log". A probe shim splits that
in two: it paints the cont_splash framebuffer white, waits, then calls PSCI
SYSTEM_RESET. The screen and the reboot itself become the signal.

Two earlier attempts to reuse the repo's BootShim/BootShimProbe.S both
produced a 192-byte shim whose _Payload sat at 0xc0 -- byte-for-byte the stock
shim -- even though the CI compiler line plainly showed -DPROBE_RESET=1 and
BootShimProbe.S on the command line. Rather than keep debugging that file, the
probe assembly is emitted here from a literal in this script, so what gets
compiled is what is written in this file. The object is then disassembled and
the run refuses to continue unless the probe marker (smc) is present.

Addresses come from this unit's own runtime device tree:
  fdt_dts/runtime_merged.dts:721  splash_region
    reg = <0x00 0xfc800000 0x00 0x2b00000>
which is the same extent ace6Pkg already declares as Display_Reserved.
"""
import argparse
import gzip
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
MKBOOTIMG = REPO / "Resources" / "Scripts" / "mkbootimg.py"
SHIM_DIR = REPO / "BootShim"

FB_BASE = 0xFC800000
FB_FILL = 0x100000   # 1 MiB, well inside the 43 MiB splash region
FB_MARK2_OFFSET = 0x600000   # second band, ~1/3 down a 1272x2800x4 buffer

PSCI_SYSTEM_RESET = 0x84000009

SHIM_SOURCE = r"""
// Generated by make_probe_image.py -- do not edit in place.
//
// Stage 1: paint FB_FILL bytes at FB_BASE white, then PSCI SYSTEM_RESET.
// White plus a reboot proves this code ran and the framebuffer address is
// right. A reboot with a black screen proves execution with a wrong address.
// No reboot at all means execution never reached us.
//
// Stage 2 (PROBE_RESET=0) falls through to the stock behaviour: copy the FD
// to FD_BASE and branch into it.

_Head:
  adr   x1, _Payload
  b     _Start

#if REQUIRES_KERNEL_HEADER == 1
_StackBase:
  .quad FD_BASE
_StackSize:
  .quad FD_SIZE + (_Payload - _Head)
  .quad 0
  .quad 0
  .quad 0
  .quad 0
  .ascii "ARM\x64"
  .long 0
#endif

_Start:
  mov   x11, x1
  mov   x12, x0

  /* Marker: fill the top of the scan-out buffer white. */
  ldr   x0, =FB_BASE
  ldr   x2, =FB_FILL
  mov   x3, #-1
_Paint:
  stp   x3, x3, [x0], #16
  subs  x2, x2, #16
  b.ne  _Paint
  dsb   sy

#if PROBE_RESET == 1
  /* Hold the marker so it is visible before the deliberate reset. */
  mrs   x4, cntfrq_el0
  cbnz  x4, 1f
  ldr   x4, =19200000
1:
  mov   x5, #PROBE_DELAY_S
  mul   x4, x4, x5
  isb
  mrs   x5, cntpct_el0
  add   x4, x4, x5
2:
  isb
  mrs   x5, cntpct_el0
  cmp   x5, x4
  b.lo  2b

  mov   w0, #0x9
  movk  w0, #0x8400, lsl #16
  mov   x1, xzr
  mov   x2, xzr
  mov   x3, xzr
  smc   #0
_Dead:
  wfe
  b     _Dead
#else
  mov   x0, x12
  mov   x4, x11
  ldr   x5, =FD_BASE
  cmp   x4, x5
  beq   _Entry
  ldr   x6, =FD_SIZE

_CopyLoop:
  ldp   x2, x3, [x4], #16
  stp   x2, x3, [x5], #16
  subs  x6, x6, #16
  b.ne  _CopyLoop
  ldr   x5, =FD_BASE

  /* Mark 2: the FD copy completed. Painted further down the panel so the
     stage is readable from the screen alone:
       one band then reset   the copy itself faulted
       two bands then reset  the copy finished, the FD entry faulted
       two bands then blank  SEC ran and cleared Display_Reserved */
  ldr   x0, =(FB_BASE + FB_MARK2_OFFSET)
  ldr   x2, =FB_FILL
  mov   x3, #-1
_Mark2:
  stp   x3, x3, [x0], #16
  subs  x2, x2, #16
  b.ne  _Mark2
  dsb   sy

_Entry:
  /* Publish the copied instructions before executing them. */
  dsb   sy
  mrs   x9, ctr_el0
  ubfx  x9, x9, #16, #4
  mov   x10, #4
  lsl   x9, x10, x9
  sub   x10, x9, #1
  bic   x8, x5, x10
  ldr   x7, =FD_SIZE
  add   x7, x5, x7

_CleanLoop:
  dc    cvac, x8
  add   x8, x8, x9
  cmp   x8, x7
  b.lo  _CleanLoop
  dsb   sy
  ic    iallu
  dsb   sy
  isb
  br    x5
#endif

.text
.ltorg
.align 4

_Payload:
"""


def run(cmd, cwd=None):
    print("  $ " + " ".join(str(c) for c in cmd), flush=True)
    r = subprocess.run([str(c) for c in cmd], cwd=cwd)
    if r.returncode != 0:
        print(f"  FAILED (exit {r.returncode})", flush=True)
        return False
    return True


def capture(cmd, cwd=None):
    r = subprocess.run([str(c) for c in cmd], cwd=cwd,
                       capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fd", required=True, help="path to SILICIUM_UEFI.fd")
    ap.add_argument("--dtb", required=True, help="device tree to append")
    ap.add_argument("--out", required=True, help="output boot image")
    ap.add_argument("--reset", type=int, default=1,
                    help="1 = paint then reboot, 0 = paint then enter the FD")
    ap.add_argument("--delay", type=int, default=10,
                    help="seconds to hold the marker before reset")
    ap.add_argument("--clang", default="clang")
    ap.add_argument("--objcopy", default="llvm-objcopy")
    ap.add_argument("--objdump", default="llvm-objdump")
    ap.add_argument("--fd-base", default="0xa7100000")
    ap.add_argument("--fd-size", default="0x300000")
    args = ap.parse_args()

    fd = Path(args.fd)
    dtb = Path(args.dtb)
    for p in (fd, dtb, MKBOOTIMG):
        if not p.is_file():
            print(f"  MISSING {p}")
            return 1

    SHIM_DIR.mkdir(parents=True, exist_ok=True)
    src = SHIM_DIR / "ProbeShim.S"
    elf = SHIM_DIR / "ProbeShim.elf"
    bin_ = SHIM_DIR / "ProbeShim.bin"

    src.write_text(SHIM_SOURCE, encoding="ascii")
    print(f"  wrote {src} ({len(SHIM_SOURCE)} chars)", flush=True)

    defs = [
        "-DREQUIRES_KERNEL_HEADER=1",
        f"-DFD_BASE={args.fd_base}",
        f"-DFD_SIZE={args.fd_size}",
        f"-DFB_BASE={FB_BASE:#x}",
        f"-DFB_FILL={FB_FILL:#x}",
        f"-DFB_MARK2_OFFSET={FB_MARK2_OFFSET:#x}",
        f"-DPROBE_RESET={args.reset}",
        f"-DPROBE_DELAY_S={args.delay}",
    ]

    if not run([args.clang, "--target=aarch64-linux-gnu", "-c", src.name,
                "-o", elf.name] + defs, cwd=SHIM_DIR):
        return 1
    if not run([args.objcopy, "-O", "binary", elf.name, bin_.name],
               cwd=SHIM_DIR):
        return 1

    shim = bin_.read_bytes()
    print(f"  shim {len(shim)} B", flush=True)
    print(f"  shim head: {shim[:32].hex()}", flush=True)

    # Self-check on the object, not on trust.
    code, dis = capture([args.objdump, "-d", "--no-show-raw-insn", elf.name],
                        cwd=SHIM_DIR)
    if code != 0 or not dis.strip():
        print("  FAIL could not disassemble the probe object")
        return 1
    has_smc = re.search(r"\bsmc\b", dis) is not None
    has_wfe = re.search(r"\bwfe\b", dis) is not None
    print(f"  self-check: smc={has_smc} wfe={has_wfe}", flush=True)
    for line in dis.splitlines():
        s = line.strip()
        if s and (s.startswith("0:") or "smc" in s or "wfe" in s):
            print(f"    {line.rstrip()}", flush=True)
    if args.reset == 1 and not (has_smc and has_wfe):
        print("  FAIL probe path absent from the object")
        return 1

    payload = shim + fd.read_bytes()
    kernel_gz = gzip.compress(payload, 9)
    kernel = kernel_gz + dtb.read_bytes()
    print(f"  payload shim {len(shim)} + fd {fd.stat().st_size}", flush=True)
    print(f"  kernel {len(kernel_gz)} B gz + dtb {dtb.stat().st_size} B",
          flush=True)

    tmp = Path(args.out).with_suffix(".kernel.bin")
    tmp.write_bytes(kernel)
    try:
        ok = run([sys.executable, MKBOOTIMG,
                  "--kernel", tmp,
                  "--header_version", "4",
                  "-o", args.out])
    finally:
        tmp.unlink(missing_ok=True)

    if ok:
        out = Path(args.out)
        print(f"  output {out} ({out.stat().st_size} B)", flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())